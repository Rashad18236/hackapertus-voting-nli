"""Write docs/dataset_profile.md from data/raw/v1.1.parquet.

Run from track_2a/:  python3 scripts/profile_dataset.py
Needs pandas and pyarrow (requirements-dev.txt); not part of the pipeline.
"""

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data/raw/v1.1.parquet"
OUT = ROOT / "docs/dataset_profile.md"


def md_table(frame):
    """Render a DataFrame as a Markdown table (no extra dependency)."""
    frame = frame.reset_index()
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    sep = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def main():
    df = pd.read_parquet(RAW)
    dedup = df.drop_duplicates()
    lengths = df["reference_string"].str.len()
    lines = [
        "# Dataset profile: OSTswiss/MNLIoverSwissVotingBooklets v1.1",
        "",
        "Generated by `scripts/profile_dataset.py` from `data/raw/v1.1.parquet`.",
        "All counts are on the raw file unless stated otherwise.",
        "",
        f"- Rows: {len(df)}",
        f"- Exact duplicate rows (all columns equal): {df.duplicated().sum()}",
        f"- Rows after dropping exact duplicates: {len(dedup)}",
        f"- Duplicate (claim, reference_string) pairs: {df.duplicated(['claim', 'reference_string']).sum()}",
        f"- (claim, reference_string) pairs with conflicting labels: "
        f"{(df.groupby(['claim', 'reference_string'])['entailment_label'].nunique() > 1).sum()}",
        f"- Distinct reference_string values: {df['reference_string'].nunique()}",
        f"- Distinct votes (`vote`): {df['vote'].nunique()}",
        "",
        "## Columns and types",
        "",
        md_table(pd.DataFrame({"dtype": df.dtypes.astype(str), "non_null": df.notna().sum(),
                               "distinct": df.nunique()}).rename_axis("column")),
        "",
        "There is no `booklet_language` column; `reference_language` plays that role",
        "(it always matches the language code in `booklet_url`). There is no gold",
        "evidence column.",
        "",
        "## One full example row (row 0)",
        "",
        "```json",
        json.dumps(df.iloc[0].to_dict(), ensure_ascii=False, indent=2, default=str),
        "```",
        "",
        "## Label counts",
        "",
        "0 = entailment, 1 = neutral, 2 = contradiction.",
        "",
        md_table(pd.DataFrame({"raw": df["entailment_label"].value_counts().sort_index(),
                               "deduplicated": dedup["entailment_label"].value_counts().sort_index()})
                 .rename_axis("label")),
        "",
        "## claim_language x reference_language (raw)",
        "",
        md_table(pd.crosstab(df["claim_language"], df["reference_language"])),
        "",
        "## claim_language x reference_language (deduplicated)",
        "",
        md_table(pd.crosstab(dedup["claim_language"], dedup["reference_language"])),
        "",
        "## Booklets and rows per booklet",
        "",
        "Each voting date has one booklet published in three languages (three URLs).",
        "",
        md_table(df.groupby("booklet_publish_date").agg(
            rows_raw=("claim", "size"),
            booklet_urls=("booklet_url", "nunique"),
            votes=("vote", "nunique"),
        ).join(dedup.groupby("booklet_publish_date").size().rename("rows_dedup"))),
        "",
        f"Rows per booklet URL (raw): min {df.groupby('booklet_url').size().min()}, "
        f"median {df.groupby('booklet_url').size().median():.0f}, "
        f"max {df.groupby('booklet_url').size().max()} over {df['booklet_url'].nunique()} URLs.",
        "",
        "## reference_string length (characters)",
        "",
        f"- min {lengths.min()}, median {lengths.median():.0f}, max {lengths.max()}",
        "",
        "## Other columns",
        "",
        f"- `booklet_download_date`: {', '.join(df['booklet_download_date'].unique())}",
        f"- `baseline_score`: min {df['baseline_score'].min():.3f}, median "
        f"{df['baseline_score'].median():.3f}, max {df['baseline_score'].max():.3f} "
        "(meaning undocumented; not used)",
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
