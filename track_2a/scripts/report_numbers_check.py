"""Session 16: every number in the technical report, and a file where it is found (read-only; no model calls).

Run from track_2a/:

    python3 scripts/report_numbers_check.py [--report technical_report.md] [--out docs/report_numbers_check.md]

Numbers are taken from the report's text outside code spans (`...`), links and the heading line: decimals
(0.977), integers with or without thousands separators (1,259; 300), and the parts of ranges (0.08–0.11). Sources,
searched in this order: the run folders' run.json, NOTES.md and other *.json files at the top of a run folder or one
level below (docs/runs/<run>/, docs/runs/<run>/<arm>/; not predictions or raw answers), then the Markdown files in
docs/ (session reports, analyses; not the generated results.md and decisions.md), README.md and the decisions files.
A report number with d decimals is found when a source holds a number that rounds to it at d decimals (0.9767 is
found for 0.977; 1258.7 for 1,259). The first file where it is found is printed; a number found nowhere is MISSING.

The check says where a number can be traced, not that it is used correctly in context: it is a list for a reader,
who reads the line and the file side by side.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NUMBER = re.compile(r"(?<![\w.])(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+\.\d+|\d+)(?![\w])")


def numbers_in(text):
    """(value as float, decimals, text) for every number token in text."""
    out = []
    for m in NUMBER.finditer(text):
        raw = m.group(1)
        clean = raw.replace(",", "")
        decimals = len(clean.split(".")[1]) if "." in clean else 0
        out.append((float(clean), decimals, raw))
    return out


def strip_code(line):
    line = re.sub(r"`[^`]*`", " ", line)
    line = re.sub(r"https?://\S+", " ", line)
    return line


def json_numbers(value, acc):
    if isinstance(value, bool):
        return
    if isinstance(value, (int, float)):
        acc.add(float(value))
    elif isinstance(value, dict):
        for v in value.values():
            json_numbers(v, acc)
    elif isinstance(value, list):
        for v in value:
            json_numbers(v, acc)
    elif isinstance(value, str):
        for v, _, _ in numbers_in(value):
            acc.add(v)


def source_files():
    runs = ROOT / "docs" / "runs"
    first = []
    for folder in sorted(p for p in runs.iterdir() if p.is_dir()):
        for f in sorted(folder.glob("*.json")) + sorted(folder.glob("*/*.json")) + sorted(folder.glob("NOTES.md")):
            if f.name not in ("snapshot.json", "replay_table.json"):
                first.append(f)
    docs = [p for p in sorted((ROOT / "docs").glob("*.md")) if p.name not in ("results.md", "decisions.md")]
    return first + docs + [ROOT / "README.md"] + sorted((ROOT / "docs" / "decisions").glob("*.md"))


def index(files):
    found = []
    for f in files:
        values = set()
        try:
            if f.suffix == ".json":
                json_numbers(json.loads(f.read_text(encoding="utf-8")), values)
            else:
                for v, _, _ in numbers_in(f.read_text(encoding="utf-8")):
                    values.add(v)
        except (ValueError, UnicodeDecodeError):
            continue
        found.append((f, values))
    return found


def locate(value, decimals, idx):
    for f, values in idx:
        for v in values:
            if (round(v, decimals) == round(value, decimals)) if decimals else round(v) == value:
                return f
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--report", default=str(ROOT / "technical_report.md"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "report_numbers_check.md"))
    args = ap.parse_args()
    idx = index(source_files())
    rows, missing = [], 0
    for n, line in enumerate(Path(args.report).read_text(encoding="utf-8").splitlines(), 1):
        if n == 1:
            continue
        for value, decimals, raw in numbers_in(strip_code(line)):
            f = locate(value, decimals, idx)
            status = "OK" if f else "MISSING"
            missing += f is None
            rows.append(f"| {n} | {raw} | {status} | {f.relative_to(ROOT) if f else ''} |")
    head = [f"# Numbers of `{Path(args.report).name}` and where they are found", "",
            f"Generated by `scripts/report_numbers_check.py`: {len(rows)} numbers, {len(rows) - missing} OK, "
            f"{missing} MISSING.", "", "| Line | Number | Status | First file where found |", "|---|---|---|---|"]
    Path(args.out).write_text("\n".join(head + rows) + "\n", encoding="utf-8")
    print(f"{len(rows)} numbers, {len(rows) - missing} OK, {missing} MISSING -> {args.out}")
    for r in rows:
        if "MISSING" in r:
            print(r)


if __name__ == "__main__":
    main()
